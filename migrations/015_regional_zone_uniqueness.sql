-- 015  กันโซนใบรับรองระดับภูมิภาคซ้ำซ้อน
--
-- จนถึงตอนนี้ยังไม่มีโค้ดไหนเขียนตาราง regional_certifications เลย มีแต่
-- สคริปต์ย้ายข้อมูล 009 กับ seed-demo ซึ่งทั้งคู่จับกลุ่มตามจังหวัดอยู่แล้ว
-- โซนจึงไม่เคยซ้ำกันมาก่อน
--
-- พอเปิดให้แอดมินสร้างโซนเองจากหน้าเว็บ ทางที่จะเกิดโซนซ้ำก็เปิดขึ้นทันที
-- สองคนพิมพ์ชื่อเดียวกันคนละเวลา หรือคนเดิมลืมว่าเคยสร้างไว้แล้ว
--
-- โซนซ้ำไม่ได้พังแบบเห็นชัด แต่ทำให้สวนในพื้นที่เดียวกันกระจายไปคนละโซน
-- พอใบต่ออายุ แอดมินแก้โซนหนึ่งแล้วอีกโซนค้างของเก่าไว้ สวนสองกลุ่มจะแสดง
-- ข้อมูลใบเดียวกันไม่ตรงกัน ซึ่งเป็นเหตุผลที่ 005 แยกตารางนี้ออกมาแต่แรก
--
-- บังคับที่ฐาน ไม่ใช่ที่โค้ด เพราะการตรวจในโค้ดข้ามได้ด้วยการยิง SQL ตรง
-- และเพราะการตรวจแล้วค่อยเขียนมีช่องว่างระหว่างสองจังหวะเสมอ
--
-- ปลอดภัยกับฐานที่ใช้งานอยู่ เป็นการเพิ่มดัชนีอย่างเดียว ไม่แก้และไม่ลบข้อมูล
-- ถ้าข้อมูลเดิมมีแถวที่ชนกันอยู่แล้ว การสร้างดัชนีจะล้มทั้งไฟล์และไม่มีอะไร
-- ถูกเปลี่ยน ซึ่งเป็นผลที่ต้องการ ดีกว่าสร้างสำเร็จครึ่งเดียว
-- ============================================================================

BEGIN;

-- ----------------------------------------------------------------------------
-- ชื่อโซนที่ต่างกันแค่ช่องว่างหรือตัวพิมพ์ ถือเป็นชื่อเดียวกัน
--
-- 005 มี UNIQUE (certification_type_id, region_name) อยู่แล้ว แต่เทียบข้อความ
-- ตรง ๆ 'ทุเรียนภูเขาไฟศรีสะเกษ' กับ 'ทุเรียนภูเขาไฟ ศรีสะเกษ' และ
-- 'ทุเรียนภูเขาไฟศรีสะเกษ ' (มีช่องว่างท้าย) จึงผ่านได้ทั้งสามแบบ
--
-- ลบช่องว่างทิ้งทั้งหมด ไม่ใช่แค่ยุบให้เหลือช่องเดียว เพราะภาษาไทยไม่ได้ใช้
-- ช่องว่างคั่นคำ 'ทุเรียนภูเขาไฟ ศรีสะเกษ' กับ 'ทุเรียนภูเขาไฟศรีสะเกษ'
-- คือชื่อเดียวกันที่พิมพ์คนละแบบ ไม่ใช่คนละชื่อ
--
-- ต้องระบุอักขระเองด้วย ไม่พึ่ง \s อย่างเดียว เพราะ \s ไม่จับ NBSP กับ ZWSP
-- (ตรวจกับ Postgres ตัวจริงแล้ว) ซึ่งเป็นสองตัวที่ติดมาบ่อยที่สุดตอน
-- คัดลอกชื่อจากเว็บหน่วยงาน และมองไม่เห็นบนหน้าจอเลย
--
-- ค่าที่เก็บจริงยังเป็นชื่อที่แอดมินพิมพ์ทุกตัวอักษร ตัวที่ถูกล้างคือกุญแจ
-- ที่ใช้เทียบเท่านั้น
--
-- ภาษาไทยไม่มีตัวพิมพ์ใหญ่เล็ก แต่ชื่อโซนใส่อักษรโรมันปนได้ จึงคลุม lower ไว้ด้วย
-- ทุกฟังก์ชันที่ใช้เป็น IMMUTABLE จึงสร้างเป็นดัชนีนิพจน์ได้
-- ----------------------------------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS regional_certifications_name_normalized_idx
  ON regional_certifications (
    certification_type_id,
    lower(regexp_replace(region_name, E'[[:space:]\u00A0\u200B\u200C\u200D\uFEFF]', '', 'g'))
  );

-- ----------------------------------------------------------------------------
-- เลขทะเบียนใบเดียวกันเป็นของสองโซนไม่ได้
--
-- ด่านที่ตรงกับความจริงที่สุด ใบ GI หนึ่งใบมีเลขทะเบียนของตัวเองใบเดียว
-- ถ้ามีสองโซนถือเลขเดียวกัน แปลว่ามีคนสร้างโซนซ้ำแน่นอน ไม่ว่าจะตั้งชื่อ
-- ต่างกันแค่ไหนก็ตาม ซึ่งเป็นกรณีที่ดัชนีชื่อข้างบนจับไม่ได้
--
-- เป็น partial index เพราะเลขที่ใบไม่บังคับกรอก โซนที่ยังไม่รู้เลขที่
-- ต้องสร้างได้หลายโซน ถ้าคลุมค่าว่างด้วย โซนที่สองที่ยังไม่กรอกเลขจะสร้างไม่ได้เลย
-- ----------------------------------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS regional_certifications_cert_number_idx
  ON regional_certifications (certification_type_id, cert_number)
  WHERE cert_number IS NOT NULL AND btrim(cert_number) <> '';

-- ----------------------------------------------------------------------------
-- ใช้หาโซนที่มีอยู่แล้วในจังหวัดที่แอดมินกำลังจะสร้างโซนใหม่
--
-- ไม่ใช่ดัชนีเอกลักษณ์ เพราะจังหวัดหนึ่งมีใบระดับโซนได้มากกว่าหนึ่งใบจริง ๆ
-- เช่นจังหวัดที่ขึ้นทะเบียน GI ทุเรียนไว้สองสายพันธุ์ การบังคับหนึ่งโซน
-- ต่อหนึ่งจังหวัดจะทำให้ใบที่สองขึ้นทะเบียนไม่ได้เลย
--
-- หน้าที่ของมันคือให้เซิร์ฟเวอร์เตือนแอดมินได้เร็วว่าจังหวัดนี้มีโซนอยู่แล้ว
-- แล้วให้คนเป็นผู้ตัดสินว่าเป็นคนละโซนจริงหรือกำลังจะสร้างซ้ำ
-- ----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS regional_certifications_type_province_idx
  ON regional_certifications (certification_type_id, province);

COMMIT;
