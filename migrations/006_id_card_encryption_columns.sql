-- ============================================================================
-- 006  คอลัมน์สำหรับเก็บเลขบัตรและรูปบัตรที่เข้ารหัสแล้ว
--
-- ปลอดภัยกับฐานข้อมูลที่ใช้งานอยู่ เพิ่มคอลัมน์ว่างอย่างเดียว
-- ยังไม่เขียนข้อมูล ยังไม่ลบคอลัมน์เดิม โค้ดที่รันอยู่ตอนนี้ไม่รู้จักคอลัมน์เหล่านี้
-- และยังทำงานได้ตามปกติ
--
-- การเข้ารหัสทำที่ฝั่งแอปด้วย AES-256-GCM ของ Node ไม่ใช่ pgcrypto
-- เหตุผลคือ pgcrypto ต้องส่งกุญแจเข้ามาเป็นพารามิเตอร์ของคำสั่ง SQL ทุกครั้ง
-- กุญแจจึงมีโอกาสไปโผล่ใน log_statement, pg_stat_activity หรือ pg_stat_statements
-- ส่วนการเข้ารหัสฝั่งแอปทำให้กุญแจอยู่ในโปรเซส Node เท่านั้น
-- Postgres สายเน็ตเวิร์ก และ log เห็นแต่ ciphertext
-- ตรงกับวิธีที่ระบบนี้ถือ JWT_SECRET อยู่แล้ว
--
-- ไม่มีคอลัมน์ HMAC สำหรับค้นเลขซ้ำโดยตั้งใจ เลขบัตรไทยมีความเป็นไปได้เพียง
-- 10^12 แบบ (12 หลักอิสระ หลักที่ 13 คำนวณได้) HMAC-SHA256 ไม่ใช่ memory-hard
-- ถ้า pepper หลุดมาพร้อมฐานข้อมูล ซึ่งในระบบนี้อยู่ไฟล์ .env เดียวกัน
-- การไล่เดาครบทุกความเป็นไปได้ใช้เวลาระดับนาทีบนการ์ดจอตัวเดียว
-- เท่ากับล้มการเข้ารหัสทั้งหมด เพื่อฟีเจอร์ที่ยังไม่มีใครใช้
-- ============================================================================

BEGIN;

ALTER TABLE farm_requests
  -- nonce ‖ ciphertext ‖ authTag ประกอบกันเป็นก้อนเดียว
  -- ผูก id ของแถวเป็น AAD ตอนเข้ารหัส ciphertext จึงย้ายข้ามแถวไม่ได้
  -- ถ้ามีคนสลับก้อนข้อมูลระหว่างแถว การถอดรหัสจะล้มทันที ไม่ใช่คืนเลขของคนผิดคน
  ADD COLUMN IF NOT EXISTS farmer_id_card_ciphertext       bytea,

  -- รูปบัตรเข้ารหัสด้วยกุญแจและวิธีเดียวกัน
  -- ถ้าเข้ารหัสแต่ตัวเลขแล้วปล่อยรูปไว้ คนที่ dump ฐานข้อมูลได้ก็เปิดรูปดูได้อยู่ดี
  -- ซึ่งในรูปมีทั้งเลขบัตร ชื่อ ที่อยู่ และรูปหน้า มากกว่าตัวเลขที่เราเข้ารหัสเสียอีก
  ADD COLUMN IF NOT EXISTS farmer_id_card_photo_ciphertext bytea,

  -- หลักที่ 13 ของเลขบัตร เก็บแยกไว้เพื่อประกอบการแสดงผลแบบปิดบัง
  -- X-XXXX-XXXXX-XX-8 โดยไม่ต้องถอดรหัสทุกครั้งที่แสดงรายการ
  --
  -- เปิดเผยได้เพราะหลักนี้เป็นหลักตรวจสอบ คำนวณจาก 12 หลักแรกได้อยู่แล้ว
  -- จึงไม่ได้ให้ข้อมูลอะไรเพิ่มแก่ผู้โจมตี ต่างจากสี่หลักท้ายที่กินหลักที่ 10-13
  -- ซึ่งมีสาระจริงสามหลัก และเป็นชุดที่ธนาคารกับค่ายมือถือใช้ยืนยันตัวตน
  ADD COLUMN IF NOT EXISTS farmer_id_card_check_digit      text
    CHECK (farmer_id_card_check_digit IS NULL OR farmer_id_card_check_digit ~ '^[0-9]$'),

  -- เผื่อการหมุนกุญแจในอนาคต ตอนนี้ยังมีกุญแจชุดเดียวและยังไม่มีกลไกหมุน
  -- คอลัมน์นี้เป็นแค่ที่รองรับ ไม่ได้แปลว่าหมุนกุญแจได้แล้ว
  ADD COLUMN IF NOT EXISTS id_card_key_version             smallint NOT NULL DEFAULT 1;

COMMIT;
