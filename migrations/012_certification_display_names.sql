-- 012  ชื่อใบรับรองที่ใช้แสดงผล ให้กลับไปเหมือนข้อความเดิมของระบบ
--
-- หลังขาอ่านย้ายมาที่ตารางชุดใหม่ ชื่อที่หน้าเว็บแสดงมาจาก certification_types
-- ที่เดียว แทนที่จะเป็นข้อความอิสระของแต่ละแถวแบบตารางเก่า ผลคือป้ายชื่อ
-- เปลี่ยนไปจากที่ผู้ใช้เคยเห็น
--
--   GAP  'GAP (Good Agricultural Practice)'  กลายเป็น  'มาตรฐาน GAP'
--   GI   'GI สิ่งบ่งชี้ทางภูมิศาสตร์'          กลายเป็น  'สิ่งบ่งชี้ทางภูมิศาสตร์'
--
-- หน้าเว็บแสดง name_th ก่อน ถ้าไม่มีจึงใช้ name ไฟล์นี้จึงแก้ที่ name_th
-- ของสองประเภทที่มีข้อมูลเดิมอยู่จริง ส่วน name ที่เป็นชื่อสากลไม่ถูกแตะ
--
-- แก้ที่ข้อมูล ไม่ใช่ที่โค้ด อยากเปลี่ยนป้ายชื่ออีกก็ UPDATE ตารางนี้ได้เลย
-- ============================================================================

BEGIN;

UPDATE certification_types
   SET name_th = 'GAP (Good Agricultural Practice)'
 WHERE code = 'GAP';

UPDATE certification_types
   SET name_th = 'GI สิ่งบ่งชี้ทางภูมิศาสตร์'
 WHERE code = 'GI';

COMMIT;
