-- ============================================================================
-- 008  บันทึกการเปิดดูข้อมูลบัตรประชาชน
--
-- ปลอดภัยกับฐานข้อมูลที่ใช้งานอยู่ สร้างตารางใหม่อย่างเดียว ไม่แตะของเดิม
--
-- ทำไมต้องมี
--   ระบบนี้ยังไม่มีการทำ audit log ที่ไหนเลย ถ้าข้อมูลบัตรประชาชนรั่ว
--   จะไม่มีทางรู้เลยว่าใครเปิดดูอะไรไปบ้าง ซึ่งจำเป็นต่อการแจ้งเหตุ
--   ภายใน 72 ชั่วโมงตาม พ.ร.บ.คุ้มครองข้อมูลส่วนบุคคล
--
--   การเข้ารหัสกันคนที่ dump ฐานข้อมูลได้ แต่ไม่ได้กันแอดมินที่มีสิทธิ์อยู่แล้ว
--   สิ่งที่กันคนกลุ่มหลังได้คือการรู้ว่าใครดูอะไรเมื่อไหร่
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS id_card_access_log (
  id              bigserial   PRIMARY KEY,

  -- ใคร -- uid ของแอดมินที่กดดู มาจาก token ไม่ได้รับจาก body
  admin_user_id   text        NOT NULL,

  -- ดูของใคร -- id ของคำขอที่ถูกเปิดดู
  --
  -- จงใจไม่ผูก FK ไป farm_requests เพราะบันทึกการเข้าถึงต้องอยู่ได้นานกว่า
  -- ตัวข้อมูลที่ถูกเข้าถึง ถ้าผูก FK แล้ววันหนึ่งลบคำขอทิ้งตามนโยบายเก็บข้อมูล
  -- ประวัติการเข้าดูจะหายตามไปด้วย ซึ่งขัดกับเหตุผลที่มีตารางนี้ตั้งแต่แรก
  farm_request_id text        NOT NULL,

  -- เมื่อไหร่
  accessed_at     timestamptz NOT NULL DEFAULT now(),

  -- ผลของการเรียก บันทึกทั้งที่สำเร็จและไม่สำเร็จ
  -- ความพยายามที่ล้มเหลวซ้ำ ๆ เป็นสัญญาณที่ต้องเห็น ไม่ใช่สิ่งที่ควรเงียบ
  --
  --   success        เปิดดูได้จริง
  --   not_found      ขอดูคำขอที่ไม่มีอยู่
  --   decrypt_failed ถอดรหัสไม่ผ่าน ข้อมูลอาจถูกแก้ไขหรือกุญแจไม่ตรง
  --   forbidden      คนที่ไม่ใช่แอดมินพยายามเรียก
  --   rate_limited   แอดมินยิงถี่จนชนเพดาน ซึ่งคือสัญญาณการกวาดข้อมูลโดยตรง
  --
  -- สองอันหลังถูกปฏิเสธก่อนถึงตัว route จึงต้องบันทึกจากชั้น middleware
  -- ถ้าไม่บันทึก สัญญาณที่ชัดที่สุดของการใช้งานผิดปกติจะหายไปทั้งหมด
  outcome         text        NOT NULL
                              CHECK (outcome IN ('success', 'not_found', 'decrypt_failed',
                                                 'forbidden', 'rate_limited')),

  -- ช่วยแยกว่าเป็นเครื่องไหน เผื่อบัญชีแอดมินถูกใช้จากที่แปลก ๆ
  ip              text
);

-- ไล่ดูตามเวลาเป็นการใช้งานหลัก ตอนสอบสวนเหตุมักเริ่มจาก "ช่วงเวลานี้มีใครดูอะไรบ้าง"
CREATE INDEX IF NOT EXISTS id_card_access_log_accessed_at_idx
  ON id_card_access_log (accessed_at DESC);

-- ตอบคำถาม "แอดมินคนนี้ดูอะไรไปบ้าง"
CREATE INDEX IF NOT EXISTS id_card_access_log_admin_idx
  ON id_card_access_log (admin_user_id, accessed_at DESC);

-- ตอบคำถาม "คำขอใบนี้ถูกใครเปิดดูบ้าง" ซึ่งเป็นคำถามที่เจ้าของข้อมูลมีสิทธิ์ถาม
CREATE INDEX IF NOT EXISTS id_card_access_log_request_idx
  ON id_card_access_log (farm_request_id, accessed_at DESC);

COMMIT;
