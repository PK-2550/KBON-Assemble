/**
 * ชื่อโซนใบรับรองระดับภูมิภาค -- การล้างค่าและกุญแจที่ใช้เทียบว่าซ้ำกันไหม
 *
 * อยู่ใน shared เพราะทั้งเซิร์ฟเวอร์และหน้าเว็บต้องตัดสินเรื่องเดียวกัน
 * ถ้าสองฝั่งล้างค่าไม่เหมือนกัน หน้าเว็บจะบอกว่าชื่อนี้ใช้ได้ แล้วเซิร์ฟเวอร์
 * ปฏิเสธทีหลัง ซึ่งดูเหมือนระบบพังทั้งที่กฎถูกต้อง
 *
 * และต้องให้ผลตรงกับดัชนีใน migration 015 ด้วย ถ้าชั้นเซิร์ฟเวอร์หลวมกว่าฐาน
 * ผู้ใช้จะเจอ error ดิบจากฐานข้อมูลแทนข้อความที่อ่านรู้เรื่อง
 */

/**
 * อักขระที่มองไม่เห็นแต่ทำให้ข้อความต่างกัน
 *
 * ZWSP ZWNJ ZWJ และ BOM ติดมาบ่อยเวลาคัดลอกชื่อจากหน้าเว็บหน่วยงาน
 * ไม่กินที่บนจอเลย ชื่อสองชื่อจึงดูเหมือนกันเป๊ะทั้งที่ระบบเห็นเป็นคนละค่า
 */
// ตั้งใจลบทีละอักขระ ไม่ได้จับเป็นกลุ่มสัญลักษณ์ และชุดนี้ต้องตรงกับดัชนีใน migration 015
// eslint-disable-next-line no-misleading-character-class
const ZERO_WIDTH = /[\u200B\u200C\u200D\uFEFF]/g;

/**
 * ช่องว่างทุกชนิดรวม NBSP
 *
 * ต้องระบุ NBSP เองเพราะนิพจน์ปกติของฝั่งฐานข้อมูลไม่จับให้ (ตรวจกับ
 * Postgres ตัวจริงแล้ว) การเขียนให้ตรงกันทั้งสองฝั่งสำคัญกว่าความสั้น
 */
const ANY_SPACE = /[\s\u00A0]+/g;

/**
 * ชื่อที่จะเก็บลงฐาน
 *
 * เก็บไว้ให้อ่านเหมือนที่แอดมินพิมพ์มา ตัดแค่ช่องว่างหัวท้ายกับที่ซ้อนกัน
 * และล้างอักขระล่องหนทิ้ง เพราะถ้าปล่อยไว้ชื่อจะดูปกติบนจอแต่ค้นหาไม่เจอ
 */
export function cleanZoneName(raw: string): string {
  return raw.replace(ZERO_WIDTH, '').replace(ANY_SPACE, ' ').trim();
}

/**
 * กุญแจที่ใช้เทียบว่าเป็นชื่อเดียวกันหรือไม่
 *
 * ลบช่องว่างทิ้งทั้งหมด ไม่ใช่แค่ยุบให้เหลือช่องเดียว เพราะภาษาไทยไม่ได้ใช้
 * ช่องว่างคั่นคำ 'ทุเรียนภูเขาไฟ ศรีสะเกษ' กับ 'ทุเรียนภูเขาไฟศรีสะเกษ'
 * คือชื่อเดียวกันที่พิมพ์คนละแบบ ไม่ใช่คนละโซน
 *
 * ภาษาไทยไม่มีตัวพิมพ์ใหญ่เล็ก แต่ชื่อโซนใส่อักษรโรมันปนได้ จึงลดรูปด้วย
 */
export function normalizeZoneNameKey(raw: string): string {
  return raw.replace(ZERO_WIDTH, '').replace(ANY_SPACE, '').toLowerCase();
}
